-- Milestone 6a: the three modules that finally make the EXPOSURE and NETWORK
-- scoring categories real (both previously scored a hardcoded 100 since no
-- module produced findings in them), plus WHOIS/RDAP domain-registration
-- monitoring. WHOIS findings use their own 'WHOIS' category (already present
-- in bloodhound-common's Category enum) which is deliberately NOT one of the
-- six categories in ScoringEngine.CATEGORY_WEIGHTS - they show up in the
-- findings list/UI but do not affect the overall score, since the plan's
-- fixed weight table has no slot for them.

CREATE TABLE whois_records (
    id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    target_id        UUID NOT NULL REFERENCES targets(id) ON DELETE CASCADE,
    captured_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    registrar        TEXT,
    created_date     TIMESTAMPTZ,
    expiry_date      TIMESTAMPTZ,
    registrant_org   TEXT,
    name_servers     JSONB,
    raw_jsonb        JSONB NOT NULL DEFAULT '{}'
);

-- Append-only history table (no unique constraint) - WHOIS_REGISTRANT_CHANGED
-- diffs the two most recent rows for a target.
CREATE INDEX idx_whois_records_target_captured ON whois_records(target_id, captured_at DESC);

